import { strToU8, zipSync } from "fflate"
import { themeVariables } from "@/lib/governance"
import { COLOR_STEPS, type ThemeTokens } from "@/lib/token-schema"
import { contrastRatio } from "./color"

// The client's delivery bundle: published block sources, the theme as CSS for
// Tailwind v4, the raw token file, and a Tokens Studio file that imports the
// same values into Figma variables. Pure: returns the zip bytes.

export type BundleBlock = {
  name: string
  source: string
  version: number
}

export type BundleInput = {
  clientId: string
  layoutLabel: string
  tokens: ThemeTokens
  background: string
  blocks: BundleBlock[]
}

function slug(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")
}

const isDark = (hex: string) => contrastRatio(hex, "#ffffff") > contrastRatio(hex, "#000000")

/** First step, in preference order, that reaches `min` contrast on `background`. */
function readableStep(scale: ThemeTokens["colors"]["secondary"], order: (keyof typeof scale)[], background: string, min = 4.5) {
  return scale[order.find((step) => contrastRatio(scale[step], background) >= min) ?? order[order.length - 1]]
}

/** shadcn variables for :root, driven by the client's tokens and page background. */
export function themeCss(tokens: ThemeTokens, background: string) {
  const vars = themeVariables(tokens, ["button", "input", "card", "badge", "dialog", "navbar", "tooltip"])
  const { secondary } = tokens.colors
  const dark = isDark(background)

  // Surfaces follow the page background: light tints on light pages, deep
  // shades on dark ones, with text steps checked against AA rather than assumed.
  const surfaces: Record<string, string> & { "--foreground": string } = dark
    ? {
        "--foreground": readableStep(secondary, ["50", "100", "200"], background),
        "--muted": secondary["900"],
        "--muted-foreground": readableStep(secondary, ["300", "200", "100", "50"], background),
        "--border": secondary["800"],
        "--input": secondary["800"],
        "--secondary": secondary["800"],
        "--secondary-foreground": secondary["50"],
        "--accent": secondary["900"],
        "--accent-foreground": secondary["50"],
      }
    : {
        "--foreground": readableStep(secondary, ["950", "900", "800"], background),
        "--muted": secondary["50"],
        "--muted-foreground": readableStep(secondary, ["700", "800", "900", "950"], background),
        "--border": secondary["200"],
        "--input": secondary["200"],
      }

  const root: Record<string, string> = {
    ...vars,
    ...surfaces,
    "--background": background,
    "--card": background,
    "--card-foreground": surfaces["--foreground"],
    "--popover": background,
    "--popover-foreground": surfaces["--foreground"],
    "--destructive": dark ? "#f87171" : "#dc2626",
  }
  for (const scale of ["primary", "secondary"] as const) {
    for (const step of COLOR_STEPS) {
      root[`--color-${scale}-${step}`] = tokens.colors[scale][step]
    }
  }
  for (const [step, value] of Object.entries(tokens.radius)) {
    root[`--radius-${step}`] = value
  }

  const mapped = [
    "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
    "primary", "primary-foreground", "secondary", "secondary-foreground", "muted",
    "muted-foreground", "accent", "accent-foreground", "destructive", "border", "input", "ring",
  ]

  return `/* Generated by Tulip from the client's approved tokens. Import after "tailwindcss". */

:root {
${Object.entries(root).map(([name, value]) => `  ${name}: ${value};`).join("\n")}
}

@theme inline {
${mapped.map((name) => `  --color-${name}: var(--${name});`).join("\n")}
}
`
}

/** Tokens Studio for Figma (single "global" set), importable as Figma variables. */
export function tokensStudioJson(tokens: ThemeTokens, background: string) {
  const color = (value: string) => ({ value, type: "color" })
  const px = (value: string) => String(value.endsWith("rem") ? Number.parseFloat(value) * 16 : Number.parseFloat(value))
  return {
    global: {
      primary: Object.fromEntries(COLOR_STEPS.map((step) => [step, color(tokens.colors.primary[step])])),
      secondary: Object.fromEntries(COLOR_STEPS.map((step) => [step, color(tokens.colors.secondary[step])])),
      background: color(background),
      radius: Object.fromEntries(
        Object.entries(tokens.radius).map(([step, value]) => [step, { value: px(value), type: "borderRadius" }]),
      ),
      fontFamilies: {
        heading: { value: tokens.typography.heading[0], type: "fontFamilies" },
        body: { value: tokens.typography.body[0], type: "fontFamilies" },
        mono: { value: tokens.typography.mono[0], type: "fontFamilies" },
      },
    },
    $themes: [],
    $metadata: { tokenSetOrder: ["global"] },
  }
}

function readme(input: BundleInput) {
  const rows = input.blocks
    .map((b) => `| ${b.name} | \`components/blocks/${slug(b.name)}.tsx\` | v${b.version} |`)
    .join("\n")
  return `# ${input.clientId} UI bundle

Generated by Tulip for the ${input.layoutLabel} layout. Every block passed the automated taste audit and a human operator review before publishing.

## Contents

| Block | File | Version |
| --- | --- | --- |
${rows}

- \`styles/tulip-theme.css\`: your tokens as shadcn/Tailwind v4 variables.
- \`tokens/tokens.json\`: the canonical token file (also served over MCP at \`tulip://tokens/${input.clientId}\`).
- \`tokens/tokens-studio.json\`: import with the Tokens Studio plugin to create matching Figma variables.

## Setup

1. Install the shadcn primitives the blocks import: \`npx shadcn@latest add button card input ...\` (see each file's imports).
2. In \`app/globals.css\`, after \`@import "tailwindcss";\`, add \`@import "../styles/tulip-theme.css";\`.
3. Load your fonts (${input.tokens.typography.heading[0]}, ${input.tokens.typography.mono[0]}) with \`next/font\` or your font host.
4. Copy \`components/blocks\` into your app and render the blocks.
`
}

export function buildBundle(input: BundleInput) {
  const files: Record<string, Uint8Array> = {
    "README.md": strToU8(readme(input)),
    "styles/tulip-theme.css": strToU8(themeCss(input.tokens, input.background)),
    "tokens/tokens.json": strToU8(`${JSON.stringify(input.tokens, null, 2)}\n`),
    "tokens/tokens-studio.json": strToU8(`${JSON.stringify(tokensStudioJson(input.tokens, input.background), null, 2)}\n`),
  }
  for (const block of input.blocks) {
    files[`components/blocks/${slug(block.name)}.tsx`] = strToU8(block.source)
  }
  return zipSync(files, { level: 9 })
}
